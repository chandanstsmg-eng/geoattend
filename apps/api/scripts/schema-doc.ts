/**
 * Writes docs/DATABASE-SCHEMA.md from a throw-away database built by the real migrations.
 *   npm run db:schema-doc
 * Touches no existing database; refuses to run with DATABASE_URL set.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { REPO_ROOT } from '../src/config.js';
import { closePool, initPool, q } from '../src/db/pool.js';
import { dropDatabase, ensureDatabase } from '../src/db/postgres.js';
import { migrate } from '../src/db/migrate.js';

if (process.env.DATABASE_URL) throw new Error('db:schema-doc uses a throw-away embedded database; unset DATABASE_URL.');
const name = `geoattend_schema_${Date.now()}_${crypto.randomBytes(3).toString('hex')}`;
const pool = initPool(await ensureDatabase(name));
const out: string[] = [];
try {
  await migrate(pool);
  const tables = await q<{ table_name: string }>(`SELECT table_name FROM information_schema.tables WHERE table_schema = 'public' AND table_type = 'BASE TABLE' ORDER BY 1`);
  const views = await q<{ table_name: string }>(`SELECT table_name FROM information_schema.views WHERE table_schema = 'public' AND table_name NOT IN ('geography_columns', 'geometry_columns') ORDER BY 1`);
  const migrations = (await fs.promises.readdir(path.join(REPO_ROOT, 'apps/api/src/db/migrations'))).filter((f) => f.endsWith('.sql')).sort();
  out.push(
    '# Database schema',
    '',
    `Generated by \`npm run db:schema-doc\` from migrations up to \`${migrations.at(-1)}\`. Do not edit by hand.`,
    '',
    `${tables.length} tables, ${views.length} views.`,
    '',
  );
  for (const { table_name: t } of tables) {
    const cols = await q(
      `SELECT column_name, data_type, udt_name, is_nullable, column_default FROM information_schema.columns
       WHERE table_schema = 'public' AND table_name = $1 ORDER BY ordinal_position`,
      [t],
    );
    const cons = await q(
      `SELECT conname, contype, pg_get_constraintdef(oid) AS def FROM pg_constraint
       WHERE conrelid = ('public.' || quote_ident($1))::regclass ORDER BY contype, conname`,
      [t],
    );
    const idx = await q(`SELECT indexdef FROM pg_indexes WHERE schemaname = 'public' AND tablename = $1 ORDER BY indexname`, [t]);
    const trg = await q(`SELECT tgname FROM pg_trigger WHERE tgrelid = ('public.' || quote_ident($1))::regclass AND NOT tgisinternal ORDER BY 1`, [t]);
    out.push(`## ${t}`, '', '| Column | Type | Null | Default |', '|---|---|---|---|');
    for (const c of cols) {
      const type = c.data_type === 'USER-DEFINED' || c.data_type === 'ARRAY' ? c.udt_name : c.data_type;
      out.push(`| ${c.column_name} | ${type} | ${c.is_nullable === 'YES' ? 'yes' : ''} | ${c.column_default ? `\`${String(c.column_default).replaceAll('|', '\\|')}\`` : ''} |`);
    }
    out.push('');
    if (cons.length) out.push('Constraints:', '', ...cons.map((c) => `- \`${c.conname}\`: \`${String(c.def).replace(/\s+/g, ' ')}\``), '');
    const plain = idx.map((i) => String(i.indexdef).replace(/^CREATE /, '').replace(' ON public.', ' ON '));
    if (plain.length) out.push('Indexes:', '', ...plain.map((i) => `- \`${i}\``), '');
    if (trg.length) out.push(`Triggers: ${trg.map((x) => `\`${x.tgname}\``).join(', ')}`, '');
  }
  if (views.length) {
    out.push('## Views', '');
    for (const { table_name: v } of views) {
      const [d] = await q(`SELECT pg_get_viewdef(('public.' || quote_ident($1))::regclass, true) AS def`, [v]);
      out.push(`### ${v}`, '', '```sql', String(d.def).trim(), '```', '');
    }
  }
} finally {
  await closePool();
  await dropDatabase(name);
}
fs.writeFileSync(path.join(REPO_ROOT, 'docs/DATABASE-SCHEMA.md'), `${out.join('\n').trimEnd()}\n`);
console.log('  Wrote docs/DATABASE-SCHEMA.md');
process.exit(0);
